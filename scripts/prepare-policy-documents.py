"""Rebuild local PDF page images and selectable text: Python + pdfplumber/Pillow + Poppler."""
import json
import subprocess
import tempfile
from pathlib import Path

import pdfplumber
from PIL import Image

ROOT = Path(__file__).resolve().parents[1]
DEST = ROOT / 'legacy/prototypes/policy-issuance/assets/documents'
DOCUMENTS = [
    ('rules', 'Правила страхования'),
    ('key-information', 'Ключевой информационный документ'),
    ('policy-offer', 'Образец полиса-оферты'),
]
imports = ["// Generated by scripts/prepare-policy-documents.py; do not edit page data by hand."]
entries = []
for identifier, title in DOCUMENTS:
    folder = DEST / identifier
    folder.mkdir(exist_ok=True)
    page_data = []
    with pdfplumber.open(DEST / (identifier + '.pdf')) as pdf, tempfile.TemporaryDirectory() as temp:
        subprocess.run(['pdftoppm', '-png', '-scale-to', '1800', str(DEST / (identifier + '.pdf')), temp + '/page'], check=True)
        renders = sorted(Path(temp).glob('page-*.png'))
        assert len(renders) == len(pdf.pages)
        for number, (page, rendered) in enumerate(zip(pdf.pages, renders), 1):
            filename = f'page-{number:02}.webp'
            with Image.open(rendered) as image:
                image.save(folder / filename, 'WEBP', quality=92, method=6)
            words = page.extract_words(x_tolerance=2, y_tolerance=3)
            text = [{'text': word['text'], 'x': round(word['x0'], 3), 'y': round(word['top'], 3),
                     'width': round(word['x1'] - word['x0'], 3), 'height': round(word['bottom'] - word['top'], 3)}
                    for word in words if word['x1'] > word['x0'] and word['bottom'] > word['top']]
            # This PDF draws most of its text as outlines. Vision runs only at preparation time.
            if identifier == 'key-information':
                recognized = subprocess.check_output(['swift', str(ROOT / 'scripts/ocr-document-page.swift'), str(rendered)])
                text = [{**word, 'x': round(word['x'] * page.width, 3), 'y': round(word['y'] * page.height, 3),
                         'width': round(word['width'] * page.width, 3), 'height': round(word['height'] * page.height, 3)}
                        for word in json.loads(recognized)]
            page_data.append({
                'width': round(page.width, 3), 'height': round(page.height, 3),
                'text': text,
            })
            imports.append(f"import {identifier.replace('-', '_')}_{number} from './{identifier}/{filename}';")
    (folder / 'pages.json').write_text(json.dumps(page_data, ensure_ascii=False, separators=(',', ':')) + '\n')
    variable = identifier.replace('-', '_')
    imports.append(f"import {variable}Pages from './{identifier}/pages.json';")
    urls = ', '.join(f'{variable}_{n}' for n in range(1, len(page_data) + 1))
    entries.append("  { id: '" + identifier + "', title: '" + title + "', pages: " + variable +
                   'Pages.map(function (page, index) { return Object.assign({}, page, { src: [' + urls + '][index] }); }) }')
    print(identifier, len(page_data), 'pages;', sum(len(page['text']) for page in page_data), 'text items')
(DEST / 'index.js').write_text('\n'.join(imports) + '\n\nexport default [\n' + ',\n'.join(entries) + '\n];\n')
(DEST / 'index.d.ts').write_text("import type { LegacyModalDocument } from '../../../../components/documents-modal/index.js';\ndeclare const documents: LegacyModalDocument[];\nexport default documents;\n")
